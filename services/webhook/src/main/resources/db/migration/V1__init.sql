-- Webhook Delivery Service schema (database webhook_db, user webhook_svc).
-- Runs on PostgreSQL in every environment and on H2 (PostgreSQL mode) in the tests, hence no text columns.

-- Events this service has consumed from webhook.q; the event id is recorded first, so a redelivered event is ignored.
create table processed_events (
    event_id      varchar(64)              primary key,
    event_type    varchar(100)             not null,
    processed_at  timestamp with time zone not null
);

-- One row per (merchant, event): what is POSTed, where, and how the last attempt went.
-- The signing secret is never stored; it is fetched from the Merchant Service for each attempt.
create table webhook_deliveries (
    id                    uuid                     primary key,
    merchant_id           uuid                     not null,
    event_id              varchar(64)              not null,
    event_type            varchar(100)             not null,
    url                   varchar(2048)            not null,
    -- exact JSON body that is POSTed (the event envelope); larger events are rejected to the DLQ
    payload               varchar(65536)           not null,
    correlation_id        varchar(64)              not null,
    status                varchar(16)              not null,
    attempts              integer                  not null default 0,
    last_http_status      integer,
    duration_ms           bigint,
    error                 varchar(300),
    response_snippet      varchar(512),
    -- JSON object of the last request headers, signature shortened
    last_request_headers  varchar(4000),
    created_at            timestamp with time zone not null,
    updated_at            timestamp with time zone not null,
    last_attempt_at       timestamp with time zone,
    next_attempt_at       timestamp with time zone,
    replay_count          integer                  not null default 0,
    last_replayed_by      varchar(100),
    version               bigint                   not null default 0,
    constraint uq_webhook_deliveries_merchant_event unique (merchant_id, event_id),
    constraint ck_webhook_deliveries_status check (status in ('PENDING', 'RETRYING', 'DELIVERED', 'FAILED'))
);

create index ix_webhook_deliveries_created on webhook_deliveries (created_at desc);
create index ix_webhook_deliveries_merchant_created on webhook_deliveries (merchant_id, created_at desc);
create index ix_webhook_deliveries_status_created on webhook_deliveries (status, created_at desc);
create index ix_webhook_deliveries_event_type on webhook_deliveries (event_type);

-- Append-only log of every HTTP attempt of a delivery.
create table webhook_delivery_attempts (
    id                bigint generated by default as identity primary key,
    delivery_id       uuid                     not null references webhook_deliveries (id) on delete cascade,
    attempt_no        integer                  not null,
    attempted_at      timestamp with time zone not null,
    http_status       integer,
    duration_ms       bigint                   not null,
    outcome           varchar(16)              not null,
    error             varchar(300),
    response_snippet  varchar(512),
    constraint uq_webhook_delivery_attempts_no unique (delivery_id, attempt_no),
    constraint ck_webhook_delivery_attempts_outcome check (outcome in ('SUCCESS', 'RETRY', 'FAILED'))
);
